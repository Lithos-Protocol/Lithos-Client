import org.bouncycastle.util.encoders.Hex
import scorex.crypto.hash.Blake2b256

/** Pool asset layout: native pools hold ERG as X; token pools hold a token as X. */
sealed trait PoolShape
object PoolShape {
  /** ERG against a token. Pool tokens are NFT, LP, Y — the ERG side is the box value. */
  case object Native extends PoolShape
  /** Token against token. Pool tokens are NFT, LP, X, Y. */
  case object Token extends PoolShape
}

/** What an order asks the pool to do. */
sealed trait OrderKind
object OrderKind {
  /** Spend the X asset to receive Y. On a native pool, ERG in. */
  case object SwapSell extends OrderKind
  /** Spend the Y asset to receive X. On a native pool, ERG out. */
  case object SwapBuy extends OrderKind
  /** Add both sides and receive LP tokens. */
  case object Deposit extends OrderKind
  /** Return LP tokens to the pool and receive both reserve assets. */
  case object Redeem extends OrderKind
}

/** Order template and execution support; per-order terms are read from segregated constants. */
final case class OrderContract(kind: OrderKind,
                               shape: PoolShape,
                               version: String,
                               templateHex: String,
                               executable: Boolean) {

  val name: String = s"${shape.getClass.getSimpleName.stripSuffix("$").toLowerCase}-" +
    s"${kind.getClass.getSimpleName.stripSuffix("$").toLowerCase}-$version"

  /** Node indexer hash, derived with Blake2b256 from the template bytes. */
  lazy val templateHash: String = Hex.toHexString(Blake2b256(Hex.decode(templateHex)))
}

